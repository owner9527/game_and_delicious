  /* ---------------- 解析 ---------------- */
  const SOLID = new Set(["#", "="]);
  const DEADLY = new Set(["^", "!"]);
  const PASS_DEVICES = new Set([">", "<", "/", "\\", "q", "j", "*", "o", "O", "u", "U"]);

  function parseLevel(def, chapterTheme) {
    const rows = def.map.slice();
    const H = rows.length;
    let W = 0;
    for (const r of rows) W = Math.max(W, r.length);
    const FW = W * 2;
    // 网格：先填左半，再镜像右半
    const grid = [];
    for (let y = 0; y < H; y++) {
      const row = new Array(FW).fill(".");
      for (let x = 0; x < W; x++) {
        const c = (rows[y][x] || ".");
        row[x] = c;
        row[FW - 1 - x] = FLIP[c] || c;
      }
      grid.push(row);
    }
    // 右岸非对称覆盖
    if (def.right) {
      for (let y = 0; y < Math.min(H, def.right.length); y++) {
        const rr = def.right[y];
        for (let x = 0; x < W; x++) {
          const c = rr[x];
          if (c && c !== " ") grid[y][W + x] = c;
        }
      }
    }

    const L = {
      def, W, H, FW, grid, theme: chapterTheme,
      spawns: [], exits: [], checkpoints: [],
      shards: {},            // id -> [{x,y}]
      plates: { g: [], h: [], s: [] },
      doors: { G: [], H: [], S: [] },
      portals: [],           // {in:{x,y}, out:{x,y}}（两岸各一组，镜像自动成对）
      beats: [], grav: [], breakCells: [],
      emitters: [], mirrors: [], switchMirrors: [], pads: [], receivers: [],
      beat: def.beat || null,
      mode: def.mode, par: def.par, name: def.name, hint: def.hint, tut: def.tut,
      hasBeams: false,
    };
    const portalA = { in: [], out: [] }, portalB = { in: [], out: [] };

    for (let y = 0; y < H; y++) {
      for (let x = 0; x < FW; x++) {
        const c = grid[y][x];
        const cell = { x, y };
        switch (c) {
          case "P": L.spawns.push(cell); break;
          case "E": L.exits.push(cell); break;
          case "c": L.checkpoints.push(cell); break;
          case "1": case "2": case "3":
            (L.shards[c] = L.shards[c] || []).push(cell); break;
          case "g": case "h": case "s": L.plates[c].push(cell); break;
          case "G": case "H": case "S": L.doors[c].push(cell); break;
          case "o": portalA.in.push(cell); break;
          case "O": portalA.out.push(cell); break;
          case "u": portalB.in.push(cell); break;
          case "U": portalB.out.push(cell); break;
          case "b": L.beats.push({ ...cell, phase: 0 }); break;
          case "B": L.beats.push({ ...cell, phase: 0.5 }); break;
          case "w": L.grav.push(cell); break;
          case "z": L.breakCells.push(cell); break;
          case ">": L.emitters.push({ ...cell, dir: 1 }); L.hasBeams = true; break;
          case "<": L.emitters.push({ ...cell, dir: -1 }); L.hasBeams = true; break;
          case "/": case "\\": L.mirrors.push({ ...cell, o: c }); L.hasBeams = true; break;
          case "q": L.switchMirrors.push(cell); L.hasBeams = true; break;
          case "j": L.pads.push(cell); break;
          case "*": L.receivers.push(cell); L.hasBeams = true; break;
        }
      }
    }
    // 门自动向上延伸（最多 2 格），防止跳过
    for (const gk of Object.keys(L.doors)) {
      const extra = [];
      for (const d of L.doors[gk]) {
        let yy = d.y - 1, n = 0;
        while (yy >= 0 && n < 2 && grid[yy][d.x] === ".") { extra.push({ x: d.x, y: yy }); yy--; n++; }
      }
      L.doors[gk].push(...extra);
    }
    // 传送门配对：进入 o（左岸）→ 从对岸（右岸）的 O 出现
    function pair(ins, outs) {
      for (const i of ins) {
        const isLeft = i.x < W;
        const target = outs.find((o) => (isLeft ? o.x >= W : o.x < W));
        if (target) L.portals.push({ in: i, out: target });
      }
    }
    pair(portalA.in, portalA.out);
    pair(portalB.in, portalB.out);
    return L;
  }

  function chapterLevels(ch) { return LEVELS.filter((l) => l.ch === ch); }
  function levelByIdx(i) { return LEVELS[i]; }

  window.MMLevels = { CHAPTERS, LEVELS, parseLevel, chapterLevels, levelByIdx, SOLID, DEADLY, PASS_DEVICES };
